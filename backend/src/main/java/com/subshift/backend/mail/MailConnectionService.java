package com.subshift.backend.mail;

import com.subshift.backend.common.CurrentUserService;
import com.subshift.backend.gmail.GmailConnection;
import com.subshift.backend.gmail.GmailConnectionRepository;
import com.subshift.backend.gmail.GmailOAuthService;
import com.subshift.backend.gmail.TokenEncryptor;
import com.subshift.backend.users.User;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDateTime;
import java.util.Locale;
import java.util.regex.Pattern;

/** Provider-independent connection status and disconnect, plus connecting Yahoo (which has no OAuth step). */
@Service
@RequiredArgsConstructor
public class MailConnectionService {

    private static final Pattern YAHOO_ADDRESS =
            Pattern.compile("^[a-z0-9._%+\\-]{1,64}@(yahoo|ymail|rocketmail)\\.[a-z]{2,}(\\.[a-z]{2,})?$");

    public record StatusResponse(boolean connected, String provider, String providerLabel, String mailboxAddress,
                                 LocalDateTime connectedAt, LocalDateTime lastSyncedAt) {}

    private final CurrentUserService currentUserService;
    private final GmailConnectionRepository connectionRepository;
    private final GmailOAuthService gmailOAuthService;
    private final YahooProvider yahooProvider;
    private final TokenEncryptor encryptor;

    @Transactional(readOnly = true)
    public StatusResponse status(String email) {
        User user = currentUserService.require(email);
        return connectionRepository.findByUserId(user.getId())
                .map(c -> new StatusResponse(true, c.getProvider().name(), c.getProvider().label(),
                        c.getMailboxAddress(), c.getConnectedAt(), c.getLastSyncedAt()))
                .orElse(new StatusResponse(false, null, null, null, null, null));
    }

    public void disconnect(String email) {
        User user = currentUserService.require(email);
        GmailConnection connection = connectionRepository.findByUserId(user.getId()).orElse(null);
        if (connection == null) {
            return;
        }
        if (connection.getProvider() == ProviderType.GMAIL) {
            gmailOAuthService.disconnect(email); // also revokes the token at Google
        } else {
            // Outlook: the user can also remove SubShift under their Microsoft account's app permissions.
            // Yahoo: deleting the row deletes the stored app password; the user can delete it at Yahoo too.
            connectionRepository.delete(connection);
        }
    }

    /** Checks the login with Yahoo first, so a wrong password is reported now instead of at the first sync. */
    public StatusResponse connectYahoo(String email, String yahooAddress, String appPassword) {
        User user = currentUserService.require(email);
        String address = yahooAddress == null ? "" : yahooAddress.trim().toLowerCase(Locale.ROOT);
        String password = appPassword == null ? "" : appPassword.replaceAll("\\s+", "");
        if (!YAHOO_ADDRESS.matcher(address).matches()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Enter a Yahoo address (yahoo.com, ymail.com ...)");
        }
        if (password.length() < 8 || password.length() > 100) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Enter the app password generated by Yahoo");
        }
        connectionRepository.findByUserId(user.getId())
                .filter(c -> c.getProvider() != ProviderType.YAHOO)
                .ifPresent(c -> {
                    throw new ResponseStatusException(HttpStatus.CONFLICT,
                            "Disconnect " + c.getProvider().label() + " before connecting Yahoo Mail");
                });

        yahooProvider.verify(address, password);

        GmailConnection connection = connectionRepository.findByUserId(user.getId())
                .orElseGet(GmailConnection::new);
        connection.setUser(user);
        connection.useProvider(ProviderType.YAHOO);
        connection.setMailboxAddress(address);
        connection.setAppPasswordEncrypted(encryptor.encrypt(password));
        connection.setAccessTokenEncrypted(null);
        connection.setRefreshTokenEncrypted(null);
        connectionRepository.save(connection);
        return status(email);
    }
}
